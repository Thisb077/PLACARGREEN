import type { LiveMatch, Team, Player } from '../types';

function makePlayer(id: number, name: string, pos: Player['position'], num: number, goals: number, assists: number): Player {
  return {
    id,
    name,
    position: pos,
    number: num,
    stats: {
      goals,
      assists,
      shots: goals * 4 + Math.floor(Math.random() * 5),
      shotsOnTarget: goals * 2 + Math.floor(Math.random() * 3),
      passes: 30 + Math.floor(Math.random() * 50),
      passAccuracy: 70 + Math.floor(Math.random() * 25),
      keyPasses: assists + Math.floor(Math.random() * 3),
      tackles: Math.floor(Math.random() * 5),
      interceptions: Math.floor(Math.random() * 4),
      fouls: Math.floor(Math.random() * 4),
      yellowCards: Math.floor(Math.random() * 2),
      redCards: 0,
      corners: pos === 'LW' || pos === 'RW' ? Math.floor(Math.random() * 8) : 0,
      dribbles: Math.floor(Math.random() * 5),
      saves: pos === 'GK' ? 20 + Math.floor(Math.random() * 20) : 0,
      minutesPerGoal: goals > 0 ? Math.round((38 * 90) / goals) : 999,
      form: 5 + Math.floor(Math.random() * 5),
    },
    isInjured: false,
    isSuspended: false,
  };
}

